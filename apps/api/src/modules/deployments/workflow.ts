/**
 * Generates the GitHub Actions workflow that deploys an environment.
 *
 * Flow: checkout -> assume the environment's deploy role via OIDC (no stored
 * AWS keys) -> build & push the image to ECR -> point the current task
 * definition at it -> roll the ECS service and wait until healthy. The ECS
 * circuit breaker (ecs-service module) rolls back deploys that never become
 * healthy.
 *
 * Pure function: everything comes from the environment's Terraform outputs,
 * so it is easy to test and to regenerate after infrastructure changes.
 */

export interface WorkflowInput {
  projectName: string;
  environmentName: string;
  /** Deploy on push to `branch`, or only when run manually. */
  trigger: "push" | "manual";
  branch: string;
  region: string;
  deployRoleArn: string;
  registryUrl: string;
  cluster: string;
  service: string;
  taskDefinitionFamily: string;
  containerName: string;
}

export function workflowPath(environmentName: string): string {
  return `.github/workflows/launchpad-deploy-${environmentName}.yml`;
}

export function renderDeployWorkflow(input: WorkflowInput): string {
  // Values come from Launchpad/Terraform (ARNs, slugs), but quote them anyway
  // so nothing can break out of YAML.
  const q = (value: string) => JSON.stringify(value);

  const on =
    input.trigger === "push"
      ? `on:
  push:
    branches: [${q(input.branch)}]
  workflow_dispatch: {}`
      : `on:
  # Production deploys are started by hand (Actions -> Run workflow). Add
  # required reviewers to the GitHub environment to require approval too.
  workflow_dispatch: {}`;

  return `# Generated by Launchpad for ${input.projectName} / ${input.environmentName}.
# You can edit it (e.g. the build step). If the environment's infrastructure is
# re-created, regenerate it in Launchpad so the names below stay in sync.
name: Deploy ${input.environmentName}

${on}

permissions:
  id-token: write # GitHub OIDC -> AWS; no AWS keys are stored in GitHub
  contents: read

concurrency:
  group: launchpad-deploy-${input.environmentName}
  cancel-in-progress: false # never interrupt a deploy halfway

jobs:
  deploy:
    name: Build and deploy to ${input.environmentName}
    runs-on: ubuntu-latest
    # Must match the deploy role's trust policy. Protection rules on this
    # GitHub environment (reviewers, branches) gate every deploy.
    environment: ${q(input.environmentName)}
    env:
      AWS_REGION: ${q(input.region)}
      IMAGE: ${q(`${input.registryUrl}:\${{ github.sha }}`)}
      ECS_CLUSTER: ${q(input.cluster)}
      ECS_SERVICE: ${q(input.service)}
      TASK_FAMILY: ${q(input.taskDefinitionFamily)}
      CONTAINER_NAME: ${q(input.containerName)}
    steps:
      - name: Check out
        uses: actions/checkout@v4

      - name: Authenticate to AWS (OIDC)
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: ${q(input.deployRoleArn)}
          aws-region: \${{ env.AWS_REGION }}

      - name: Log in to Amazon ECR
        uses: aws-actions/amazon-ecr-login@v2

      - name: Build and push image
        run: |
          docker build --tag "$IMAGE" .
          docker push "$IMAGE"

      - name: Fetch the current task definition
        run: |
          aws ecs describe-task-definition \\
            --task-definition "$TASK_FAMILY" \\
            --query taskDefinition > task-definition.json

      - name: Point it at the new image
        id: render
        uses: aws-actions/amazon-ecs-render-task-definition@v1
        with:
          task-definition: task-definition.json
          container-name: \${{ env.CONTAINER_NAME }}
          image: \${{ env.IMAGE }}

      - name: Deploy to ECS and wait until healthy
        uses: aws-actions/amazon-ecs-deploy-task-definition@v2
        with:
          task-definition: \${{ steps.render.outputs.task-definition }}
          cluster: \${{ env.ECS_CLUSTER }}
          service: \${{ env.ECS_SERVICE }}
          wait-for-service-stability: true
`;
}
